#!/usr/bin/env node
// Task tracker for plans/a2a-gap-closure. Dependency-free; the front matter of each tasks/T-*.md is the single source of truth.
//
//   node plans/a2a-gap-closure/tracker.mjs list                       all tasks with status
//   node plans/a2a-gap-closure/tracker.mjs next                       tasks that can start now (dependencies done)
//   node plans/a2a-gap-closure/tracker.mjs show T-03                  print the path of a task file
//   node plans/a2a-gap-closure/tracker.mjs set T-03 in_progress       change status (todo|in_progress|blocked|done|dropped)
//   node plans/a2a-gap-closure/tracker.mjs set T-03 done --note "PR #70"
//   node plans/a2a-gap-closure/tracker.mjs check                      validate ids, dependencies, statuses, cycles
//   node plans/a2a-gap-closure/tracker.mjs write                      regenerate TRACKER.md (also done by `set`)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const tasksDir = join(root, "tasks");
const STATUSES = ["todo", "in_progress", "blocked", "done", "dropped"];
const MARK = { todo: "[ ]", in_progress: "[~]", blocked: "[!]", done: "[x]", dropped: "[-]" };

function parseFrontMatter(text, file) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!match) throw new Error(`${file}: missing front matter`);
  const data = {};
  for (const line of match[1].split("\n")) {
    const pair = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (!pair) continue;
    const [, key, raw] = pair;
    data[key] = raw.startsWith("[") ? raw.slice(1, -1).split(",").map((item) => item.trim()).filter(Boolean) : raw.trim();
  }
  return data;
}

function loadTasks() {
  return readdirSync(tasksDir).filter((name) => /^T-\d+.*\.md$/.test(name)).sort().map((file) => {
    const text = readFileSync(join(tasksDir, file), "utf8");
    const data = parseFrontMatter(text, file);
    return { file, path: join(tasksDir, file), ...data, depends_on: data.depends_on ?? [] };
  });
}

function validate(tasks) {
  const problems = [];
  const ids = new Set();
  for (const task of tasks) {
    if (!task.file.startsWith(`${task.id}-`)) problems.push(`${task.file}: id "${task.id}" does not match the file name`);
    if (ids.has(task.id)) problems.push(`${task.id}: duplicate id`);
    ids.add(task.id);
    if (!STATUSES.includes(task.status)) problems.push(`${task.id}: invalid status "${task.status}"`);
  }
  for (const task of tasks) for (const dep of task.depends_on) if (!ids.has(dep)) problems.push(`${task.id}: unknown dependency ${dep}`);
  const state = new Map();
  const visit = (id, trail) => {
    if (state.get(id) === 2) return;
    if (state.get(id) === 1) { problems.push(`dependency cycle: ${[...trail, id].join(" -> ")}`); return; }
    state.set(id, 1);
    for (const dep of tasks.find((task) => task.id === id)?.depends_on ?? []) if (ids.has(dep)) visit(dep, [...trail, id]);
    state.set(id, 2);
  };
  for (const task of tasks) visit(task.id, []);
  return problems;
}

const finished = (task) => task.status === "done" || task.status === "dropped";
const runnable = (task, tasks) => task.status === "todo" &&
  task.depends_on.every((dep) => finished(tasks.find((other) => other.id === dep) ?? { status: "todo" }));

function table(tasks) {
  const rows = ["| | ID | Phase | Size | Gap | Depends on | Migration | Title |", "| --- | --- | --- | --- | --- | --- | --- | --- |"];
  for (const task of tasks) {
    rows.push(`| ${MARK[task.status] ?? "?"} | [${task.id}](tasks/${task.file}) | ${task.phase} | ${task.size} | ${task.gap ?? ""} | ${task.depends_on.join(", ") || "none"} | ${task.migration === "yes" ? "yes" : ""} | ${task.title} |`);
  }
  return rows.join("\n");
}

function writeTracker(tasks) {
  const counts = Object.fromEntries(STATUSES.map((status) => [status, tasks.filter((task) => task.status === status).length]));
  const next = tasks.filter((task) => runnable(task, tasks));
  const body = [
    "# Tracker",
    "",
    "> Generated by `node plans/a2a-gap-closure/tracker.mjs write`. Do not edit by hand: the `status` line in each task file is the source of truth.",
    "",
    `Done ${counts.done} · In progress ${counts.in_progress} · Blocked ${counts.blocked} · To do ${counts.todo} · Dropped ${counts.dropped}`,
    "",
    "Legend: `[ ]` to do, `[~]` in progress, `[!]` blocked, `[x]` done, `[-]` dropped.",
    "",
    table(tasks),
    "",
    "## Can start now",
    "",
    next.length ? next.map((task) => `- ${task.id}: ${task.title}${task.migration === "yes" ? " (adds a migration: run alone)" : ""}`).join("\n") : "- Nothing: every remaining task waits on another.",
    "",
  ].join("\n");
  writeFileSync(join(root, "TRACKER.md"), body);
}

function setStatus(tasks, id, status, note) {
  const task = tasks.find((item) => item.id === id);
  if (!task) throw new Error(`Unknown task ${id}`);
  if (!STATUSES.includes(status)) throw new Error(`Status must be one of ${STATUSES.join(", ")}`);
  if (status === "in_progress" && !runnable({ ...task, status: "todo" }, tasks) && task.status !== "in_progress" && task.status !== "blocked") {
    const open = task.depends_on.filter((dep) => !finished(tasks.find((other) => other.id === dep)));
    throw new Error(`${id} waits on ${open.join(", ")}`);
  }
  if (status === "in_progress" && task.migration === "yes") {
    const other = tasks.find((item) => item.id !== id && item.migration === "yes" && item.status === "in_progress");
    if (other) throw new Error(`${other.id} also adds a migration and is in progress; migrations are numbered, so run them one at a time`);
  }
  let text = readFileSync(task.path, "utf8");
  const today = new Date().toISOString().slice(0, 10);
  text = text.replace(/^status:.*$/m, `status: ${status}`).replace(/^updated:.*$/m, `updated: ${today}`);
  if (note) text = text.replace(/(## Implementation log\n)/, `$1\n- ${today} · ${status}: ${note}`);
  writeFileSync(task.path, text);
}

const [command, ...args] = process.argv.slice(2);
let tasks = loadTasks();
try {
  switch (command) {
    case "list": console.log(table(tasks)); break;
    case "next": {
      const active = tasks.filter((task) => task.status === "in_progress" || task.status === "blocked");
      if (active.length) console.log(`In progress or blocked:\n${active.map((task) => `  ${task.id} ${task.status}: ${task.title}`).join("\n")}\n`);
      const next = tasks.filter((task) => runnable(task, tasks));
      console.log(next.length ? `Can start now:\n${next.map((task) => `  ${task.id}: ${task.title}\n    ${join("plans/a2a-gap-closure/tasks", task.file)}`).join("\n")}` : "Nothing can start: every remaining task waits on another.");
      break;
    }
    case "show": { const task = tasks.find((item) => item.id === args[0]); if (!task) throw new Error(`Unknown task ${args[0]}`); console.log(task.path); break; }
    case "set": {
      const noteAt = args.indexOf("--note");
      setStatus(tasks, args[0], args[1], noteAt >= 0 ? args.slice(noteAt + 1).join(" ") : "");
      tasks = loadTasks();
      writeTracker(tasks);
      console.log(`${args[0]} is now ${args[1]}. TRACKER.md updated.`);
      break;
    }
    case "check": {
      const problems = validate(tasks);
      if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
      console.log(`OK: ${tasks.length} tasks, no problems.`);
      break;
    }
    case "write": writeTracker(tasks); console.log("TRACKER.md written."); break;
    default: console.log("Usage: tracker.mjs list | next | show <id> | set <id> <status> [--note text] | check | write"); process.exit(command ? 1 : 0);
  }
} catch (error) { console.error(error.message); process.exit(1); }
